"""The complex direct solve's golden vectors -- SciPy SuperLU's answers, read by BOTH languages.

Companion to `tests/unit/test_linear_port_golden.py`, whose docstring states why the Rust `direct`
(faer) is CHARACTERIZED against SuperLU at a residual-based tolerance and never equated to it. The
same holds over the complex scalars; `crates/numerics/tests/golden_complex_linear.rs` is the Rust half.

Complex numbers are frozen as separate real and imaginary arrays, because JSON has no complex type.

## The floors this file holds

- a complex-symmetric (``A = A^T``, not Hermitian) and a general non-Hermitian fixture;
- a pinned fixture whose prescribed values carry an imaginary part, pinned through the real
  `apply_dirichlet_triplets`;
- a badly scaled fixture solved by `solve_equilibrated`;
- at least one fixture REFUSED by the singular guard.

Regenerate deliberately: ``python -c "from tests.unit.test_complex_linear_port_golden import write; write()"``.
"""

from __future__ import annotations

import importlib
import json

import numpy as np
import pytest
import scipy.sparse as sp
from scipy.sparse.linalg import spsolve
from tests.port_goldens import GOLDENS, load_golden, register

from numerics_lab.linear import LinearSolveError, apply_dirichlet_triplets, solve_equilibrated, solve_linear_system

_GOLDEN = GOLDENS / 'linear_complex.json'


def _complex_symmetric(n=16):
    """Complex-symmetric tridiagonal, diagonally dominant; integer recurrences, no RNG."""
    main = np.array([complex(4.0 + (i * 0.37) % 1.0, 1.5 + (i * 0.61) % 1.0) for i in range(n)])
    off = np.array([complex(-1.0, 0.5 + 0.1 * (i % 3)) for i in range(n - 1)])
    return sp.diags([off, main, off], offsets=[-1, 0, 1], format='csr')


def _general(n=16):
    """General non-Hermitian, non-symmetric: different couplings above and below, plus a far entry."""
    main = np.array([complex(3.0 + (i % 5) / 4.0, -2.0 + (i % 3) / 2.0) for i in range(n)])
    a = sp.diags(
        [np.full(n - 1, complex(-1.0, -0.75)), main, np.full(n - 1, complex(-0.5, 0.25))],
        offsets=[-1, 0, 1],
        format='lil',
    )
    a[0, n - 1] = complex(0.3, 0.9)
    return a.tocsr()


def _rhs(n):
    return np.array([complex(((i % 7) - 3.0) / 2.0, 1.0 + (i % 3)) for i in range(n)])


def _pinned(n=12):
    """`_general` with two groups pinned to complex values through `apply_dirichlet_triplets`."""
    a = sp.coo_matrix(_general(n))
    rhs = _rhs(n)
    row, col, val = apply_dirichlet_triplets(
        a.row, a.col, a.data, rhs, {complex(1.5, -2.0): [0], complex(0.0, 0.5): [n - 1]}, 0.25
    )
    return sp.coo_matrix((val, (row, col)), shape=(n, n)).tocsr(), rhs, [0, n - 1]


def _badly_scaled(n=9):
    """``D0 M D0`` with ``D0`` spanning 1e-60..1e60: every entry finite, ``M`` well-conditioned."""
    d = np.array([10.0 ** (60 * ((i % 3) - 1)) for i in range(n)])
    scale = sp.diags(d)
    return (scale @ _complex_symmetric(n) @ scale).tocsr(), d * _rhs(n)


def _singular():
    """Two identical rows -- the guard MUST refuse."""
    r = [complex(2.0, 1.0), complex(1.0, -1.0), complex(1.0, 0.5)]
    a = np.array([r, r, [1.0, complex(1.0, 1.0), 3.0]], dtype=complex)
    return sp.csr_matrix(a), np.array([1.0, 2.0, 1.0], dtype=complex)


def _split(values) -> dict:
    values = np.asarray(values, dtype=complex)
    return {'re': [float(v) for v in values.real], 'im': [float(v) for v in values.imag]}


def _entry(a, b, *, how: str, refused: bool = False, pinned: list[int] | None = None) -> dict:
    coo = sp.coo_matrix(a)
    entry: dict = {
        'matrix': {
            'n': int(coo.shape[0]),
            'rows': [int(v) for v in coo.row],
            'cols': [int(v) for v in coo.col],
            'values': _split(coo.data),
        },
        'rhs': _split(b),
        'solve': how,
        'symmetric': bool((abs(a - a.T) > 0).nnz == 0),
        'refused_by_the_singular_guard': refused,
    }
    if pinned is not None:
        entry['pinned_indices'] = pinned
    if refused:
        with pytest.raises(LinearSolveError):
            solve_linear_system(a, b, linear_solver='direct')
        return entry
    x = solve_equilibrated(a, b) if how == 'equilibrated' else spsolve(sp.csc_matrix(a), b)
    entry['solution'] = _split(x)
    entry['residual'] = float(np.linalg.norm(a @ x - b) / np.linalg.norm(b))
    return entry


def _build() -> dict:
    pinned_a, pinned_b, pinned_idx = _pinned()
    scaled_a, scaled_b = _badly_scaled()
    sing_a, sing_b = _singular()
    return {
        'note': (
            'Generated by tests/unit/test_complex_linear_port_golden.py from SciPy spsolve (SuperLU) '
            'and numerics_lab.linear.solve_equilibrated. Read by '
            'crates/numerics/tests/golden_complex_linear.rs, which characterizes faer against it '
            'at a residual-based tolerance, never bit-for-bit.'
        ),
        'cases': {
            'complex_symmetric': _entry(_complex_symmetric(), _rhs(16), how='direct'),
            'general': _entry(_general(), _rhs(16), how='direct'),
            'pinned': _entry(pinned_a, pinned_b, how='direct', pinned=pinned_idx),
            'badly_scaled': _entry(scaled_a, scaled_b, how='equilibrated'),
            'singular_duplicate_row': _entry(sing_a, sing_b, how='direct', refused=True),
        },
    }


def write() -> None:
    """Regenerate the committed golden (deliberately; then commit it)."""
    _GOLDEN.write_text(json.dumps(_build(), sort_keys=True, separators=(',', ':')) + '\n', encoding='utf-8')


def _load() -> dict:
    if not _GOLDEN.is_file():
        pytest.fail(f'{_GOLDEN} is missing; it is a committed artifact -- regenerate it with `write()`.')
    return load_golden(_GOLDEN)


@pytest.mark.unit
def test_the_live_python_still_produces_the_frozen_complex_solutions() -> None:
    """The freeze: a behaviour change in SciPy or `solve_equilibrated` reds HERE, not in silence."""
    golden = _load()
    live = _build()
    assert set(live['cases']) == set(golden['cases']), 'the fixture set moved'
    for name, want in golden['cases'].items():
        got = live['cases'][name]
        assert got['refused_by_the_singular_guard'] == want['refused_by_the_singular_guard'], name
        if want['refused_by_the_singular_guard']:
            continue
        for part in ('re', 'im'):
            np.testing.assert_allclose(
                got['solution'][part], want['solution'][part], rtol=1e-12, atol=1e-14, err_msg=f'{name}.{part}'
            )


@pytest.mark.unit
def test_the_complex_golden_holds_its_floors() -> None:
    """A golden narrower than the thing it freezes is a scan with no floor."""
    cases = _load()['cases']
    assert cases['complex_symmetric']['symmetric']
    assert not cases['general']['symmetric']
    pinned = cases['pinned']
    assert any(pinned['rhs']['im'][i] != 0.0 for i in pinned['pinned_indices']), 'the pin carries no imaginary part'
    assert any(c['solve'] == 'equilibrated' for c in cases.values())
    assert any(c['refused_by_the_singular_guard'] for c in cases.values())


def _native_complex():
    try:
        native = importlib.import_module('numerics_lab._native')
    except ImportError:
        return None
    return getattr(native, 'solve_direct_complex', None)


@pytest.mark.unit
@pytest.mark.skipif(_native_complex() is None, reason='numerics_lab._native with solve_direct_complex not built')
def test_the_native_complex_solve_answers_what_superlu_answers_and_refuses_what_it_refuses() -> None:
    """The binding, against the same frozen SuperLU answers the Rust golden reads."""
    solve = _native_complex()
    for name, case in _load()['cases'].items():
        m = case['matrix']
        args = (
            m['n'],
            m['n'],
            np.asarray(m['rows'], dtype=np.int64),
            np.asarray(m['cols'], dtype=np.int64),
            np.asarray(m['values']['re']) + 1j * np.asarray(m['values']['im']),
            np.asarray(case['rhs']['re']) + 1j * np.asarray(case['rhs']['im']),
        )
        if case['refused_by_the_singular_guard']:
            with pytest.raises(ValueError, match='singular'):
                solve(*args)
            continue
        x = solve(*args, equilibrated=case['solve'] == 'equilibrated')
        want = np.asarray(case['solution']['re']) + 1j * np.asarray(case['solution']['im'])
        assert np.all(np.abs(x - want) <= 1e-8 * np.abs(want) + 1e-14), name


register(_GOLDEN, _build)
